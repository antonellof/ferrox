    #[test]
    fn encoder_matches_independent_python_reference() {
        let cfg = cfg();
        let weights = make_encoder_weights();
        let patches = vec![
            VIS_PATCH_0.to_vec(),
            VIS_PATCH_1.to_vec(),
            VIS_PATCH_2.to_vec(),
            VIS_PATCH_3.to_vec(),
        ];

        let out = encoder_forward(&weights, &cfg, &patches);
        assert_eq!(out.len(), VIS_GOLDEN_ENCODER_OUT.len());
        for (i, (a, b)) in out.iter().zip(VIS_GOLDEN_ENCODER_OUT.iter()).enumerate() {
            assert!((a - b).abs() < 1e-3, "element {i}: rust={a} python={b}");
        }
    }

    #[test]
    fn full_pipeline_matches_independent_python_reference() {
        let cfg = cfg();
        let encoder_weights = make_encoder_weights();
        let merger_weights = make_merger_weights();
        let patches = vec![
            VIS_PATCH_0.to_vec(),
            VIS_PATCH_1.to_vec(),
            VIS_PATCH_2.to_vec(),
            VIS_PATCH_3.to_vec(),
        ];

        let encoder_out = encoder_forward(&encoder_weights, &cfg, &patches);
        let merged = patch_merge(&encoder_out, &cfg);
        assert_eq!(merged.len(), MERGE_KH * MERGE_KW * HIDDEN_DIM); // one merged patch

        let projected = project_merged_patches(&merger_weights, &cfg, &merged, 1);
        assert_eq!(projected.len(), VIS_GOLDEN_OUTPUT.len());
        for (i, (a, b)) in projected.iter().zip(VIS_GOLDEN_OUTPUT.iter()).enumerate() {
            assert!((a - b).abs() < 1e-3, "element {i}: rust={a} python={b}");
        }
    }

    #[test]
    fn patch_merge_groups_spatially_adjacent_patches_row_major() {
        // 2x2 grid, merge kernel 2x2 -> one merged patch containing all
        // 4 original patches in (kh, kw) order: (0,0),(0,1),(1,0),(1,1).
        let hidden_dim = 1;
        let cfg = VisionConfig {
            in_dim: 1,
            patch_size: 1,
            grid_h: 2,
            grid_w: 2,
            hidden_dim,
            num_heads: 1,
            qkv_hidden: 1,
            mlp_dim: 1,
            rms_norm_eps: 1e-5,
            theta_base: 10000.0,
            merge_kh: 2,
            merge_kw: 2,
            projector_ln_eps: 1e-5,
        };
        // patch order row-major: (0,0)=10, (0,1)=20, (1,0)=30, (1,1)=40
        let encoder_out = vec![10.0, 20.0, 30.0, 40.0];
        let merged = patch_merge(&encoder_out, &cfg);
        assert_eq!(merged, vec![10.0, 20.0, 30.0, 40.0]);
    }

