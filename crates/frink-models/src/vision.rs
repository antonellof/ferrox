//! Kimi K3's MoonViT-V2 vision encoder: patch embedding -> N transformer
//! encoder layers (RMSNorm, self-attention with 2D RoPE, gated-MLP-free
//! plain MLP2 feed-forward) -> a patch-merger projector into the text
//! decoder's embedding space. Genuinely new territory for frink, which
//! has been text-only until now.
//!
//! Transcribed directly from real reference source fetched live from the
//! model repo (not guessed, not derived by analogy to other ViT/RoPE
//! designs): `moonshotai/Kimi-K3`'s `modeling_kimi_k3.py`
//! (`MoonVision3dPatchEmbed`, `Rope2DPosEmbRepeated`, `apply_rope`,
//! `MoonViTEncoderLayer`, `MoonViT3dEncoder`, `tpool_patch_merger`,
//! `PatchMergerMLPV2`) and its real `config.json`'s `vision_config`
//! (`norm_type='rmsnorm'`, `activation_func='gelu_pytorch_tanh'`,
//! `attn_bias=False`, `linear_bias=False`, `patch_embed_proj_bias=False`,
//! `patch_size=14`, `vt_hidden_size=1024`, `vt_num_attention_heads=12`,
//! `qkv_hidden_size=1536`, `vt_intermediate_size=4096`,
//! `vt_num_hidden_layers=27`, `merge_kernel_size=[2,2]`,
//! `mm_projector_type='patchmergerv2'`, `projector_ln_eps=1e-5`).
//!
//! Deliberately scoped, and disclosed as such, to the common case rather
//! than every real code path:
//! - Single image, single frame (`t=1`) -- no multi-frame video input,
//!   so the real code's temporal sincos position-embedding addition and
//!   the patch-merger's temporal-mean pooling are both no-ops here, not
//!   implemented as general code paths.
//! - The caller's patch grid is assumed to exactly match the
//!   positional-embedding grid it was constructed with, so the real
//!   code's bicubic/bilinear interpolation branch (`get_rope_shape`, for
//!   when input resolution differs from the pretrained grid) is never
//!   exercised and not implemented.
//! - One image at a time -- no variable-length multi-image batch packing
//!   (`cu_seqlens`); process a full patch sequence for one image per
//!   call.
//! - The real multimodal splicing of vision output into the text
//!   decoder's input sequence (`KimiK3ForConditionalGeneration.forward`)
//!   is out of scope here -- this module only implements the vision
//!   tower itself.
//!
//! Two real, non-obvious facts confirmed by reading source rather than
//! assuming standard ViT/RoPE conventions:
//!
//! 1. `MoonVision3dPatchEmbed.forward` reassigns `x` before calling
//!    `x.size(0)` in the same statement
//!    (`x = self.proj(x).view(x.size(0), -1)`), but Python evaluates the
//!    right-hand side of an assignment before rebinding the name, so
//!    `x.size(0)` refers to the *original*, pre-conv `x` -- meaning the
//!    real input to this module is already a batch of N individually
//!    pre-extracted `[C, patch_size, patch_size]` patches (one "image"
//!    per patch), not one whole image run through a strided conv. A
//!    `Conv2d(kernel_size=patch_size, stride=patch_size)` applied to an
//!    input exactly `patch_size` wide/tall is mathematically just one
//!    linear projection of the flattened patch -- so patch embedding
//!    here is a single shared `Linear(in_dim*patch_size*patch_size,
//!    out_dim, bias=false)` applied per patch (`WeightMatrix::apply`),
//!    not a general strided convolution.
//! 2. The 2D RoPE (`apply_rope`) rotates *consecutive* real-value pairs
//!    (`(x[2i], x[2i+1])`, the original RoFormer/GPT-NeoX convention via
//!    `view_as_complex`), NOT the "rotate half" convention
//!    (`(x[i], x[i+dim/2])`) `frink_core::attention::apply_rope`
//!    implements for the text decoder's RoPE -- a distinct function is
//!    needed here, not a reuse of that one. Within each complex pair
//!    index `j` in `[0, head_dim/2)`, `_precompute_freqs_cis` interleaves
//!    width- and height-based angles: even `j` uses the patch's width
//!    coordinate, odd `j` uses its height coordinate (confirmed by
//!    reading the actual `torch.cat(...).reshape(...)` code, which
//!    contradicts that same function's own docstring -- code wins).
//!
//! Not yet wired into `Decoder` or spliced into the text embedding
//! sequence. Tested here against synthetic weights, cross-validated
//! against an independent Python transcription of the same real
//! algorithm.

use frink_core::matmul::rms_norm;
use frink_core::weight_matrix::WeightMatrix;

#[derive(Debug, Clone, Copy)]
pub struct VisionConfig {
    pub in_dim: usize,
    pub patch_size: usize,
    pub grid_h: usize,
    pub grid_w: usize,
    pub hidden_dim: usize,
    pub num_heads: usize,
    pub qkv_hidden: usize,
    pub mlp_dim: usize,
    pub rms_norm_eps: f32,
    pub theta_base: f32,
    pub merge_kh: usize,
    pub merge_kw: usize,
    pub projector_ln_eps: f32,
}

impl VisionConfig {
    fn head_dim(&self) -> usize {
        self.qkv_hidden / self.num_heads
    }

    fn n_patches(&self) -> usize {
        self.grid_h * self.grid_w
    }
}

pub struct VisionEncoderLayerWeights {
    pub norm0_weight: Vec<f32>,
    pub wqkv: WeightMatrix, // [3*qkv_hidden, hidden_dim]
    pub wo: WeightMatrix,   // [hidden_dim, qkv_hidden]
    pub norm1_weight: Vec<f32>,
    pub fc0: WeightMatrix, // [mlp_dim, hidden_dim]
    pub fc1: WeightMatrix, // [hidden_dim, mlp_dim]
}

pub struct VisionEncoderWeights {
    pub patch_embed: WeightMatrix, // [hidden_dim, in_dim*patch_size*patch_size]
    /// Learned per-position embedding, row-major `[grid_h, grid_w,
    /// hidden_dim]` flattened, added directly to each patch's embedding
    /// (the "grid matches pretrained size, t=1" scoped case -- see
    /// module doc comment).
    pub pos_emb: Vec<f32>,
    pub layers: Vec<VisionEncoderLayerWeights>,
    pub final_norm_weight: Vec<f32>,
}

pub struct VisionMergerWeights {
    pub proj0: WeightMatrix,        // [merge_hidden, merge_hidden]
    pub proj1: WeightMatrix,        // [text_hidden, merge_hidden]
    pub post_norm_weight: Vec<f32>, // [text_hidden]
}

fn gelu_tanh(x: f32) -> f32 {
    0.5 * x * (1.0 + (0.797_884_6 * (x + 0.044715 * x * x * x)).tanh())
}

/// Abramowitz & Stegun 7.1.26 approximation, max absolute error ~1.5e-7
/// -- std has no built-in `erf`, and this is far more precise than the
/// 1e-3 tolerance any test here needs.
fn erf(x: f32) -> f32 {
    let sign = if x < 0.0 { -1.0 } else { 1.0 };
    let x = x.abs();
    let t = 1.0 / (1.0 + 0.3275911 * x);
    let poly = ((((1.061_405_4 * t - 1.453_152_1) * t) + 1.421_413_8) * t - 0.284_496_72) * t
        + 0.254_829_6;
    sign * (1.0 - poly * t * (-x * x).exp())
}

fn gelu_erf(x: f32) -> f32 {
    0.5 * x * (1.0 + erf(x / std::f32::consts::SQRT_2))
}

/// Precomputes `cos`/`sin` for every patch position's `head_dim/2`
/// rotation angles, per `Rope2DPosEmbRepeated._precompute_freqs_cis`:
/// row-major `(h, w)` position `p -> (h = p / grid_w, w = p % grid_w)`,
/// pair index `j` even uses the width coordinate, odd uses height, both
/// sharing frequency `theta_base^(-4*(j/2)/head_dim)`.
fn precompute_rope_2d(cfg: &VisionConfig) -> (Vec<f32>, Vec<f32>) {
    let head_dim = cfg.head_dim();
    assert_eq!(head_dim % 4, 0, "vision head_dim must be divisible by 4");
    let num_pairs = head_dim / 2;
    let n = cfg.n_patches();

    let mut cos_t = vec![0f32; n * num_pairs];
    let mut sin_t = vec![0f32; n * num_pairs];
    for p in 0..n {
        let x_pos = (p % cfg.grid_w) as f32;
        let y_pos = (p / cfg.grid_w) as f32;
        for j in 0..num_pairs {
            let i = j / 2;
            let freq = cfg.theta_base.powf(-4.0 * i as f32 / head_dim as f32);
            let angle = if j % 2 == 0 {
                x_pos * freq
            } else {
                y_pos * freq
            };
            cos_t[p * num_pairs + j] = angle.cos();
            sin_t[p * num_pairs + j] = angle.sin();
        }
    }
    (cos_t, sin_t)
}

/// Applies the 2D RoPE rotation in place to `x` (`[n_patches, num_heads,
/// head_dim]` flattened), the consecutive-pair convention -- see module
/// doc comment point 2.
fn apply_rope_2d(x: &mut [f32], cfg: &VisionConfig, cos_t: &[f32], sin_t: &[f32]) {
    let head_dim = cfg.head_dim();
    let num_pairs = head_dim / 2;
    for p in 0..cfg.n_patches() {
        for h in 0..cfg.num_heads {
            let base = (p * cfg.num_heads + h) * head_dim;
            for j in 0..num_pairs {
                let c = cos_t[p * num_pairs + j];
                let s = sin_t[p * num_pairs + j];
                let a = x[base + 2 * j];
                let b = x[base + 2 * j + 1];
                x[base + 2 * j] = a * c - b * s;
                x[base + 2 * j + 1] = a * s + b * c;
            }
        }
    }
}

/// Embeds a full image's patches (already extracted as flattened
/// `in_dim*patch_size*patch_size` pixel vectors, row-major `(h, w)`
/// order) and adds the learned position embedding. Returns
/// `[n_patches, hidden_dim]` flattened.
pub fn embed_patches(
    weights: &VisionEncoderWeights,
    cfg: &VisionConfig,
    patches: &[Vec<f32>],
) -> Vec<f32> {
    assert_eq!(patches.len(), cfg.n_patches());
    let mut out = Vec::with_capacity(cfg.n_patches() * cfg.hidden_dim);
    for (p, patch) in patches.iter().enumerate() {
        let embedded = weights.patch_embed.apply(patch);
        let pos = &weights.pos_emb[p * cfg.hidden_dim..(p + 1) * cfg.hidden_dim];
        for (e, po) in embedded.iter().zip(pos.iter()) {
            out.push(e + po);
        }
    }
    out
}

/// Full (non-causal) self-attention over every patch at once -- the
/// whole point of a bidirectional vision encoder, unlike the causal
/// decode-step primitives in `frink_core::attention`.
fn full_self_attention(
    q: &[f32],
    k: &[f32],
    v: &[f32],
    n_patches: usize,
    num_heads: usize,
    head_dim: usize,
) -> Vec<f32> {
    let scale = 1.0 / (head_dim as f32).sqrt();
    let mut out = vec![0f32; n_patches * num_heads * head_dim];
    for h in 0..num_heads {
        for i in 0..n_patches {
            let q_i = &q[(i * num_heads + h) * head_dim..(i * num_heads + h + 1) * head_dim];
            let mut scores = vec![0f32; n_patches];
            for t in 0..n_patches {
                let k_t = &k[(t * num_heads + h) * head_dim..(t * num_heads + h + 1) * head_dim];
                let dot: f32 = q_i.iter().zip(k_t.iter()).map(|(a, b)| a * b).sum();
                scores[t] = dot * scale;
            }
            let max = scores.iter().cloned().fold(f32::NEG_INFINITY, f32::max);
            let mut sum = 0f32;
            for s in scores.iter_mut() {
                *s = (*s - max).exp();
                sum += *s;
            }
            for s in scores.iter_mut() {
                *s /= sum;
            }
            let out_base = (i * num_heads + h) * head_dim;
            for t in 0..n_patches {
                let v_t = &v[(t * num_heads + h) * head_dim..(t * num_heads + h + 1) * head_dim];
                let w = scores[t];
                for d in 0..head_dim {
                    out[out_base + d] += w * v_t[d];
                }
            }
        }
    }
    out
}

fn encoder_layer_forward(
    layer: &VisionEncoderLayerWeights,
    cfg: &VisionConfig,
    x: &[f32],
    cos_t: &[f32],
    sin_t: &[f32],
) -> Vec<f32> {
    let n = cfg.n_patches();
    let head_dim = cfg.head_dim();

    let mut residual = x.to_vec();
    let mut normed = Vec::with_capacity(n * cfg.hidden_dim);
    for p in 0..n {
        normed.extend(rms_norm(
            &x[p * cfg.hidden_dim..(p + 1) * cfg.hidden_dim],
            &layer.norm0_weight,
            cfg.rms_norm_eps,
        ));
    }

    let mut q = vec![0f32; n * cfg.qkv_hidden];
    let mut k = vec![0f32; n * cfg.qkv_hidden];
    let mut v = vec![0f32; n * cfg.qkv_hidden];
    for p in 0..n {
        let qkv = layer
            .wqkv
            .apply(&normed[p * cfg.hidden_dim..(p + 1) * cfg.hidden_dim]);
        q[p * cfg.qkv_hidden..(p + 1) * cfg.qkv_hidden].copy_from_slice(&qkv[0..cfg.qkv_hidden]);
        k[p * cfg.qkv_hidden..(p + 1) * cfg.qkv_hidden]
            .copy_from_slice(&qkv[cfg.qkv_hidden..2 * cfg.qkv_hidden]);
        v[p * cfg.qkv_hidden..(p + 1) * cfg.qkv_hidden]
            .copy_from_slice(&qkv[2 * cfg.qkv_hidden..3 * cfg.qkv_hidden]);
    }

    apply_rope_2d(&mut q, cfg, cos_t, sin_t);
    apply_rope_2d(&mut k, cfg, cos_t, sin_t);

    let attn_out = full_self_attention(&q, &k, &v, n, cfg.num_heads, head_dim);

    for p in 0..n {
        let attn_flat = &attn_out[p * cfg.qkv_hidden..(p + 1) * cfg.qkv_hidden];
        let projected = layer.wo.apply(attn_flat);
        let res = &mut residual[p * cfg.hidden_dim..(p + 1) * cfg.hidden_dim];
        for (r, pr) in res.iter_mut().zip(projected.iter()) {
            *r += pr;
        }
    }

    let mut out = residual.clone();
    for p in 0..n {
        let res_p = &residual[p * cfg.hidden_dim..(p + 1) * cfg.hidden_dim];
        let normed1 = rms_norm(res_p, &layer.norm1_weight, cfg.rms_norm_eps);
        let mut hidden = layer.fc0.apply(&normed1);
        for h in hidden.iter_mut() {
            *h = gelu_tanh(*h);
        }
        let mlp_out = layer.fc1.apply(&hidden);
        let out_p = &mut out[p * cfg.hidden_dim..(p + 1) * cfg.hidden_dim];
        for (o, m) in out_p.iter_mut().zip(mlp_out.iter()) {
            *o += m;
        }
    }

    out
}

/// Runs the full encoder (patch embed + every layer + final norm) for
/// one image. Returns `[n_patches, hidden_dim]` flattened.
pub fn encoder_forward(
    weights: &VisionEncoderWeights,
    cfg: &VisionConfig,
    patches: &[Vec<f32>],
) -> Vec<f32> {
    let (cos_t, sin_t) = precompute_rope_2d(cfg);
    let mut x = embed_patches(weights, cfg, patches);
    for layer in &weights.layers {
        x = encoder_layer_forward(layer, cfg, &x, &cos_t, &sin_t);
    }
    let n = cfg.n_patches();
    let mut out = Vec::with_capacity(n * cfg.hidden_dim);
    for p in 0..n {
        out.extend(rms_norm(
            &x[p * cfg.hidden_dim..(p + 1) * cfg.hidden_dim],
            &weights.final_norm_weight,
            cfg.rms_norm_eps,
        ));
    }
    out
}

/// `tpool_patch_merger` for the single-frame (`t=1`) case: groups
/// spatially-adjacent `merge_kh x merge_kw` patches (row-major `(h, w)`)
/// into one merged patch each, without the temporal mean (a no-op at
/// `t=1`). Returns `[num_merged, merge_kh*merge_kw*hidden_dim]`
/// flattened -- already contiguous per merged patch, ready for the
/// projector.
pub fn patch_merge(encoder_out: &[f32], cfg: &VisionConfig) -> Vec<f32> {
    assert_eq!(cfg.grid_h % cfg.merge_kh, 0);
    assert_eq!(cfg.grid_w % cfg.merge_kw, 0);
    let new_h = cfg.grid_h / cfg.merge_kh;
    let new_w = cfg.grid_w / cfg.merge_kw;
    let merge_block = cfg.merge_kh * cfg.merge_kw;
    let mut out = vec![0f32; new_h * new_w * merge_block * cfg.hidden_dim];

    for nh in 0..new_h {
        for nw in 0..new_w {
            for kh in 0..cfg.merge_kh {
                for kw in 0..cfg.merge_kw {
                    let orig_h = nh * cfg.merge_kh + kh;
                    let orig_w = nw * cfg.merge_kw + kw;
                    let orig_patch = orig_h * cfg.grid_w + orig_w;
                    let merged_idx = nh * new_w + nw;
                    let sub_idx = kh * cfg.merge_kw + kw;
                    let src = &encoder_out
                        [orig_patch * cfg.hidden_dim..(orig_patch + 1) * cfg.hidden_dim];
                    let dst_base = (merged_idx * merge_block + sub_idx) * cfg.hidden_dim;
                    out[dst_base..dst_base + cfg.hidden_dim].copy_from_slice(src);
                }
            }
        }
    }
    out
}

/// `PatchMergerMLPV2`: per merged patch, `Linear -> GELU (erf) -> Linear
/// -> RMSNorm`. `merged` is `[num_merged, merge_kh*merge_kw*hidden_dim]`
/// flattened (`patch_merge`'s output); returns `[num_merged,
/// text_hidden]` flattened.
pub fn project_merged_patches(
    weights: &VisionMergerWeights,
    cfg: &VisionConfig,
    merged: &[f32],
    num_merged: usize,
) -> Vec<f32> {
    let merge_hidden = cfg.merge_kh * cfg.merge_kw * cfg.hidden_dim;
    let text_hidden = weights.post_norm_weight.len();
    let mut out = Vec::with_capacity(num_merged * text_hidden);
    for m in 0..num_merged {
        let input = &merged[m * merge_hidden..(m + 1) * merge_hidden];
        let mut hidden = weights.proj0.apply(input);
        for h in hidden.iter_mut() {
            *h = gelu_erf(*h);
        }
        let projected = weights.proj1.apply(&hidden);
        out.extend(rms_norm(
            &projected,
            &weights.post_norm_weight,
            cfg.projector_ln_eps,
        ));
    }
    out
}

